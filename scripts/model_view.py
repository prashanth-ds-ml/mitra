"""Write docs/MODEL_VIEW.md: the fixed text the model sees, with token estimates.

Run from the repo root:  python scripts/model_view.py
tests/test_prompt_budget.py uses the same numbers to keep each total under budget.
"""

from __future__ import annotations

import json
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OUT = ROOT / "docs" / "MODEL_VIEW.md"
BUDGET_TOKENS = 3_000  # SCOPE.md: fixed prompt + tool descriptions under ~3K tokens


def estimate_tokens(text: str) -> int:
    """Rough count: about 3.5 characters per token for English and code."""
    return math.ceil(len(text) / 3.5)


def _specs_text(specs: list[dict]) -> str:
    # One JSON object per tool, as close as we can get to what the chat
    # template puts in the prompt without running the model.
    return "\n".join(json.dumps(s, ensure_ascii=False) for s in specs)


def views() -> dict[str, list[tuple[str, str]]]:
    """{view name: [(part name, text), ...]} for the chat and `codemitra solve`."""
    from app.core import chat, loop, tools

    return {
        "Chat (`codemitra`)": [
            ("System prompt (`app.core.chat.CHAT_PROMPT`)", chat.CHAT_PROMPT),
            ('Tool specs (`app.core.chat.tool_specs("approve")`)', _specs_text(chat.tool_specs("approve"))),
        ],
        "Solve (`codemitra solve`)": [
            ("System prompt (`app.core.loop.SYSTEM_PROMPT`)", loop.SYSTEM_PROMPT),
            ("Tool specs (`app.core.tools.TOOL_SPECS`)", _specs_text(tools.TOOL_SPECS)),
        ],
    }


def totals() -> dict[str, int]:
    """Estimated tokens per view."""
    return {name: sum(estimate_tokens(text) for _, text in parts) for name, parts in views().items()}


def render() -> str:
    out = [
        "# What the model sees",
        "",
        "Generated by `python scripts/model_view.py`; do not edit by hand.",
        "",
        "Token counts are **estimates** (characters / 3.5, rounded up), not the model's tokenizer.",
        f"Budget: {BUDGET_TOKENS:,} tokens per view for the fixed prompt + tool specs "
        "(SCOPE.md; checked in CI by `tests/test_prompt_budget.py`).",
        "",
        "| View | Part | Chars | Est. tokens |",
        "|---|---|---:|---:|",
    ]
    all_views = views()
    for name, parts in all_views.items():
        for part, text in parts:
            out.append(f"| {name} | {part} | {len(text):,} | {estimate_tokens(text):,} |")
        total = sum(estimate_tokens(text) for _, text in parts)
        out.append(f"| **{name}** | **total** | | **{total:,}** |")
    for name, parts in all_views.items():
        out += ["", f"## {name}"]
        for part, text in parts:
            out += ["", f"### {part}: ~{estimate_tokens(text):,} tokens", "", "````text", text.rstrip("\n"), "````"]
    return "\n".join(out) + "\n"


def main() -> None:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    for name, total in totals().items():
        print(f"{name}: ~{total:,} tokens (budget {BUDGET_TOKENS:,})")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
